[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$SourceIdentityPath,

    [Parameter(Mandatory = $true)]
    [string]$OutputPath,

    [Parameter(Mandatory = $true)]
    [string]$ResourceOutputPath,

    [Parameter(Mandatory = $true)]
    [string]$FileDescription,

    [Parameter(Mandatory = $true)]
    [string]$OriginalFilename
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version 2.0

$identity = @([IO.File]::ReadAllLines([IO.Path]::GetFullPath($SourceIdentityPath)))
if ($identity.Count -ne 2 -or -not $identity[0].Trim() -or -not $identity[1].Trim()) {
    throw "$SourceIdentityPath must contain the version and commit on separate lines."
}
$version = $identity[0].Trim()
$commit = $identity[1].Trim()
if ($version -notmatch '^(?<major>\d+)\.(?<minor>\d+)\.(?<patch>\d+)(?:[-+].*)?$') {
    throw "VERSION.txt must begin with a three-part numeric version: $version"
}
$major = [int]$Matches.major
$minor = [int]$Matches.minor
$patch = [int]$Matches.patch

function ConvertTo-CppString {
    param([Parameter(Mandatory = $true)][string]$Value)
    return $Value.Replace('\', '\\').Replace('"', '\"')
}

$content = @(
    '// Generated by tools/build/Write-VersionHeader.ps1. Do not edit.'
    ('const char GenVersion_Version[] = "' + (ConvertTo-CppString $version) + '";')
    ('const char GenVersion_Commit[] = "' + (ConvertTo-CppString $commit) + '";')
    ''
) -join "`r`n"

$outputDirectory = Split-Path -Parent ([IO.Path]::GetFullPath($OutputPath))
[IO.Directory]::CreateDirectory($outputDirectory) | Out-Null
$encoding = New-Object Text.UTF8Encoding($false)
[IO.File]::WriteAllText($OutputPath, $content, $encoding)

$fileType = if ([IO.Path]::GetExtension($OriginalFilename) -ieq '.dll') { 'VFT_DLL' } else { 'VFT_APP' }
$internalName = [IO.Path]::GetFileNameWithoutExtension($OriginalFilename)
$prereleaseFlag = if ($version -match '-') { 'VS_FF_PRERELEASE' } else { '0x0L' }
$resourceContent = @(
    '// Generated by tools/build/Write-VersionHeader.ps1. Do not edit.'
    '#include <windows.h>'
    ''
    '#ifdef _DEBUG'
    '#define VT7PTY_DEBUG_FLAG VS_FF_DEBUG'
    '#else'
    '#define VT7PTY_DEBUG_FLAG 0x0L'
    '#endif'
    ''
    'VS_VERSION_INFO VERSIONINFO'
    " FILEVERSION $major,$minor,$patch,0"
    " PRODUCTVERSION $major,$minor,$patch,0"
    ' FILEFLAGSMASK VS_FFI_FILEFLAGSMASK'
    " FILEFLAGS VT7PTY_DEBUG_FLAG | $prereleaseFlag"
    ' FILEOS VOS_NT_WINDOWS32'
    " FILETYPE $fileType"
    ' FILESUBTYPE VFT2_UNKNOWN'
    'BEGIN'
    '    BLOCK "StringFileInfo"'
    '    BEGIN'
    '        BLOCK "040904B0"'
    '        BEGIN'
    '            VALUE "CompanyName", "VT7Pty contributors\0"'
    ('            VALUE "FileDescription", "' + $FileDescription + '\0"')
    ('            VALUE "FileVersion", "' + $version + '\0"')
    ('            VALUE "InternalName", "' + $internalName + '\0"')
    '            VALUE "LegalCopyright", "Copyright (c) WinPTY and VT7Pty contributors\0"'
    ('            VALUE "OriginalFilename", "' + $OriginalFilename + '\0"')
    '            VALUE "ProductName", "VT7Pty\0"'
    ('            VALUE "ProductVersion", "' + $version + '\0"')
    '        END'
    '    END'
    '    BLOCK "VarFileInfo"'
    '    BEGIN'
    '        VALUE "Translation", 0x0409, 1200'
    '    END'
    'END'
    ''
) -join "`r`n"

$resourceDirectory = Split-Path -Parent ([IO.Path]::GetFullPath($ResourceOutputPath))
[IO.Directory]::CreateDirectory($resourceDirectory) | Out-Null
[IO.File]::WriteAllText($ResourceOutputPath, $resourceContent, $encoding)
